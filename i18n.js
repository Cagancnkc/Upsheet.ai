const i18n = {
  lang: localStorage.getItem('ms_lang') || 'tr',

  t(key) {
    return TRANSLATIONS[this.lang]?.[key] || TRANSLATIONS['tr']?.[key] || key;
  },

  setLang(lang) {
    this.lang = lang;
    localStorage.setItem('ms_lang', lang);
    document.documentElement.lang = lang;
    this.applyAll();
    this.updateToggle();
    try { window.dispatchEvent(new CustomEvent('i18n:changed', { detail: { lang } })); } catch (_) {}
  },

  applyAll() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = val;
      } else if (el.tagName === 'META') {
        el.content = val;
      } else {
        el.textContent = val;
      }
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      el.innerHTML = this.t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.title = this.t(key);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria-label');
      el.setAttribute('aria-label', this.t(key));
    });
  },

  updateToggle() {
    const btn = document.getElementById('lang-toggle');
    if (btn) btn.textContent = this.lang === 'tr' ? 'EN' : 'TR';
  },

  toggle() {
    this.setLang(this.lang === 'tr' ? 'en' : 'tr');
  },

  init() {
    document.addEventListener('DOMContentLoaded', () => {
      this.applyAll();
      this.updateToggle();
    });
    if (document.readyState !== 'loading') {
      this.applyAll();
      this.updateToggle();
    }
  }
};

i18n.init();
window.i18n = i18n;
